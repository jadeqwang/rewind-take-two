#!/usr/bin/env python3
"""v9 fix #2 (D3): writes tools/v9/mirrors/d3_tracks.js for the new D3 (media/shots/D3/v9_take_2_push.mp4).
  plate: the sedan's front plate in the interior mirror, tracked (tools/sectionA/track_quad.py ->
         media/shots/D3/track_plate_v9.json);
  etch:  the left half of the rear window seen in the mirror glass (left of the sedan), where "me I couldn't / place"
         is etched; it follows the baked push exactly (tools/v9/mirrors/d3_push.py: zoom about PIVOT), as the mirror
         itself does not move in the take.
    $PY tools/v9/mirrors/d3_tracks.py
"""
import json
import math
import os

ROOT = "/home/jade/Documents/rewind-take-two"
PIVOT, Z_END, DUR = (1215.0, 300.0), 1.38, 3.06
ETCH0 = [940, 234, 1140, 234, 1140, 326, 940, 326]
DROP = 70.0   # d3_push.py: the picture sits 70 px lower (screen = PIVOT + (0, DROP) + z * (src - PIVOT))


def zoom(t):
    u = max(0.0, min(1.0, t / DUR))
    return 1 + (Z_END - 1) * (0.5 - 0.5 * math.cos(math.pi * u))


plate = json.load(open(os.path.join(ROOT, "media/shots/D3/track_plate_v9.json")))["keys"]   # tracked on the push clip itself
etch = [[round(i / 24, 4), [round(PIVOT[j % 2] + (DROP if j % 2 else 0) + zoom(i / 24) * (v - PIVOT[j % 2]), 1) for j, v in enumerate(ETCH0)]]
        for i in range(0, 76)]
out = os.path.join(ROOT, "tools/v9/mirrors/d3_tracks.js")
with open(out, "w") as f:
    f.write("// v9 fix #2 (D3): generated by tools/v9/mirrors/d3_tracks.py for media/shots/D3/v9_take_2_push.mp4.\n")
    f.write("// [layer_t, [TLx,TLy, TRx,TRy, BRx,BRy, BLx,BLy]] in design px, as the engine's `corners` keys.\n")
    f.write("export const D3_PLATE_V9 = " + json.dumps(plate) + ";\n")
    f.write("export const D3_ETCH_V9 = " + json.dumps(etch) + ";\n")
print("wrote", os.path.relpath(out, ROOT), len(plate), len(etch))
