#!/usr/bin/env python3
"""Collect Section A corner-pin tracks (media/shots/*/track_*.json) into render/timeline/_A_tracks.js.
Static fallbacks (FIXED) are used where a shot has no track file. Keys are [[layer_t, [TLx,TLy,TRx,TRy,BRx,BRy,BLx,BLy]], ...]."""
import json
import os

ROOT = "/home/jade/Documents/rewind-take-two"
TRACKS = {  # name -> (track json, layer-time offset: subtract the clip `in` used in A.js if the track was made from 0)
    "D1_signL": "media/shots/D1/track_signL.json",
    "D1_signR": "media/shots/D1/track_signR.json",
    "D2_top": "media/shots/D2/track_top.json",
    "D2_bot": "media/shots/D2/track_bot.json",
    "D3_etch": "media/shots/D3/track_etch.json",
    "D5_lensL": "media/shots/D5/track_lensL.json",
    "D5_lensR": "media/shots/D5/track_lensR.json",
    "D7_card": "media/shots/D7/track_card.json",
    "C4_note": "media/shots/C4/track_note.json",
}
SMOOTH = {"D5_lensL": 4, "D5_lensR": 4, "D7_card": 2}
FIXED = json.load(open(os.path.join(ROOT, "tools/sectionA/tracks_fixed.json"))) if os.path.exists(
    os.path.join(ROOT, "tools/sectionA/tracks_fixed.json")) else {}
out = ["// Corner-pin keys for Section A, generated by tools/sectionA/make_tracks.py from media/shots/*/track_*.json",
       "// (tools/sectionA/track_quad.py). Layer-local seconds. Do not edit by hand.", "export default {"]
for name, path in TRACKS.items():
    p = os.path.join(ROOT, path)
    if os.path.exists(p):
        keys = json.load(open(p))["keys"]
        if name in SMOOTH:  # moving average of the corners (jittery LK on small, low-texture quads)
            n = SMOOTH[name]
            sm = []
            for i in range(len(keys)):
                win = keys[max(0, i - n):i + n + 1]
                sm.append([keys[i][0], [round(sum(k[1][j] for k in win) / len(win), 1) for j in range(8)]])
            keys = sm
        out.append(f"  {name}: {json.dumps(keys, separators=(',', ':'))},")
    elif name in FIXED:
        out.append(f"  {name}: {json.dumps(FIXED[name])},")
    else:
        out.append(f"  {name}: [0, 0, 1, 0, 1, 1, 0, 1],")
out.append("};")
open(os.path.join(ROOT, "render/timeline/_A_tracks.js"), "w").write("\n".join(out) + "\n")
print("wrote render/timeline/_A_tracks.js")
