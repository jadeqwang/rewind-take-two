#!/usr/bin/env node
// v9 round 3: corner tracks for the D2/D3 three.js scene, straight from the scene's own rig (no tracking).
//   node tools/v9/d23/tracks_r7.mjs         -> writes tools/v9/d23/d23_tracks_r7.js (+ prints a check table); round 7: reads rig_r7.js
//   node tools/v9/d23/tracks.mjs --check    -> only the table
// Keys are [layer_t, [TLx,TLy, TRx,TRy, BRx,BRy, BLx,BLy]] in design px (1920x1080), shot-local seconds, one per frame.
// Reflected text (billboard lyric, plate) is pinned to the MIRROR IMAGE of its surface, with its corners swapped
// left<->right so it reads forward (Jade: the plate is legible "even though it should be reversed"; same cheat for the
// lyric). The glass etch sits on the glass itself (glass-local box ETCH), so it reads forward anyway.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as R from './rig_r7.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const r1 = (v) => Math.round(v * 10) / 10;
const proj = (p, cam) => { const q = R.project(p, cam); return [q.x, q.y]; };
// reflected surface quad [TL, TR, BR, BL] (as its own face reads) -> screen quad that reads forward
const mirrored = (q, cam) => { const [tl, tr, br, bl] = q.map((p) => proj(R.reflect(p), cam)); return [tr, tl, bl, br].flat(); };
const glassQuad = (cam, a0 = -1, a1 = 1, b0 = -1, b1 = 1) =>
  [R.glassPt(a0, b1), R.glassPt(a1, b1), R.glassPt(a1, b0), R.glassPt(a0, b0)].map((p) => proj(p, cam)).flat();
// where a reflected world point lands in glass-local (a, b) coordinates: intersect the ray cam -> reflect(p) with the glass
function glassLocal(p, cam) {
  const P = R.reflect(p), d = R.sub(P, cam.pos), M = R.MIRROR;
  const t = R.dot(R.sub(M.c, cam.pos), M.n) / R.dot(d, M.n);
  const x = R.sub(R.add(cam.pos, R.mul(d, t)), M.c);
  return [R.dot(x, M.u) / (M.w / 2), R.dot(x, M.v) / (M.h / 2)];
}

const shots = { D2: [R.S0, R.S1], D3: [R.S1, R.S2] };
const out = {};
const table = [];
for (const [id, [a, b]] of Object.entries(shots)) {
  const n = Math.round((b - a) * R.FPS);
  const keys = { top: [], bot: [], plate: [], etch: [], glass: [] };
  for (let i = 0; i <= n; i++) {
    const lt = i / R.FPS, s = a + lt, cam = R.camAt(s);
    const bp = R.billPanels(s);
    keys.top.push([+lt.toFixed(4), mirrored(bp.top, cam).map(r1)]);
    keys.bot.push([+lt.toFixed(4), mirrored(bp.bot, cam).map(r1)]);
    keys.plate.push([+lt.toFixed(4), mirrored(R.plateCorners(s), cam).map(r1)]);
    const E = R.ETCH;
    // round 5: the etch quad slants with the TL glass's rising bottom edge (TL, TR, BR, BL as read; a = +1 inboard is
    // screen-RIGHT seen from the camera? no: the glass is seen from its front, so -a (outboard) is screen-left)
    keys.etch.push([+lt.toFixed(4), [R.glassPt(E.a0, E.out[1]), R.glassPt(E.a1, E.in[1]), R.glassPt(E.a1, E.in[0]), R.glassPt(E.a0, E.out[0])].map((p) => proj(p, cam)).flat().map(r1)]);
    keys.glass.push([+lt.toFixed(4), glassQuad(cam).map(r1)]);
    if (i % 6 === 0) {
      const bc = R.billPanels(s), tl = glassLocal(bc.top[0], cam), br = glassLocal(bc.bot[2], cam);
      const pc = R.plateCorners(s), p0 = glassLocal(pc[0], cam), p2 = glassLocal(pc[2], cam);
      const g = keys.glass[keys.glass.length - 1][1];
      table.push(`${id} s=${s.toFixed(2)} fov=${cam.fov.toFixed(1)} glass x ${g[6].toFixed(0)}..${g[2].toFixed(0)} y ${g[1].toFixed(0)}..${g[5].toFixed(0)}` +
        ` | bill (a,b) ${tl.map((v) => v.toFixed(2))} .. ${br.map((v) => v.toFixed(2))}` +
        ` | plate ${p0.map((v) => v.toFixed(2))} .. ${p2.map((v) => v.toFixed(2))} w=${(Math.hypot(keys.plate.at(-1)[1][2] - keys.plate.at(-1)[1][0], keys.plate.at(-1)[1][3] - keys.plate.at(-1)[1][1])).toFixed(0)}px d=${R.sedanAt(s).d.toFixed(1)}`);
    }
  }
  out[id] = keys;
}
const dv = R.driverView();
table.push(`driver's view at the glass centre: ${(Math.atan2(-dv[0], dv[2]) * 180 / Math.PI).toFixed(1)} deg outward, ${(Math.asin(dv[1]) * 180 / Math.PI).toFixed(1)} deg up` +
  ` | mirror n ${R.MIRROR.n.map((v) => v.toFixed(3))}`);
const cv = R.camView();
table.push(`camera's view at the glass centre: ${(Math.atan2(-cv[0], cv[2]) * 180 / Math.PI).toFixed(1)} deg outward, ${(Math.asin(cv[1]) * 180 / Math.PI).toFixed(1)} deg up`);
console.log(table.join('\n'));
if (!process.argv.includes('--check')) {
  const js = `// v9 round 7 (D2 + D3 as one three.js scene): generated by tools/v9/d23/tracks_r7.mjs from tools/v9/d23/rig_r7.js.\n` +
    `// [layer_t, [TLx,TLy, TRx,TRy, BRx,BRy, BLx,BLy]] design px, shot-local seconds, one key per frame. Do not edit by hand.\n` +
    `// Reflected text (billboard lyric, plate) is pinned to the mirror image of its surface, corners swapped so it reads forward.\n` +
    `export const D2_BILL_TOP = ${JSON.stringify(out.D2.top)};\n` +
    `export const D2_BILL_BOT = ${JSON.stringify(out.D2.bot)};\n` +
    `export const D3_BILL_TOP = ${JSON.stringify(out.D3.top)};\n` +
    `export const D3_BILL_BOT = ${JSON.stringify(out.D3.bot)};\n` +
    `export const D3_PLATE_R3 = ${JSON.stringify(out.D3.plate)};\n` +
    `export const D3_ETCH_R3 = ${JSON.stringify(out.D3.etch)};\n` +
    `export const D2_GLASS = ${JSON.stringify(out.D2.glass)};\n` +
    `export const D3_GLASS = ${JSON.stringify(out.D3.glass)};\n`;
  const OUT = process.env.TRACKS_OUT || 'd23_tracks_r7.js';   // round 7: new file (rounds 5-6: d23_tracks_r5.js, round 4: d23_tracks.js)
  fs.writeFileSync(path.join(HERE, OUT), js);
  console.log('wrote', path.join(HERE, OUT));
}
