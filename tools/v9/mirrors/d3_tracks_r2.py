#!/usr/bin/env python3
"""v9 fix #2, round 2: writes tools/v9/mirrors/d3_tracks_r2.js for media/shots/D3/v9_take_2_push_r2.mp4.
  plate:  tracked on the r2 push clip (tools/sectionA/track_quad.py -> media/shots/D3/track_plate_v9_r2.json)
  etch_l: "me I", the rear window LEFT of the sedan, in the mirror glass
  etch_r: "couldn't / place", the rear window RIGHT of the sedan
Both etch quads follow the baked push exactly (d3_push.py: screen = PIVOT + (0, DROP) + z(t) * (src - PIVOT)); the
mirror holds within 1 px in the take. Round 1 put both lines left of the sedan in a 190x92 quad that ran onto the
mirror's bezel (the "m" was clipped).
    $PY tools/v9/mirrors/d3_tracks_r2.py
"""
import json
import os

ROOT = "/home/jade/Documents/rewind-take-two"
PIVOT, Z_END, DUR = (1215.0, 300.0), 1.9, 3.06
DROP0, DROP1 = 70.0, 0.0
ETCH_L = [990, 240, 1112, 240, 1112, 318, 990, 318]     # "me I"
ETCH_R = [1322, 240, 1452, 240, 1452, 318, 1322, 318]   # "couldn't / place"


def zoom(t):
    u = max(0.0, min(1.0, t / DUR))
    return 1 + (Z_END - 1) * (1 - (1 - u) ** 2)


def drop(t):
    return DROP0 + (DROP1 - DROP0) * (zoom(t) - 1) / (Z_END - 1)


def keys(q):
    return [[round(i / 24, 4), [round(PIVOT[j % 2] + (drop(i / 24) if j % 2 else 0) + zoom(i / 24) * (v - PIVOT[j % 2]), 1)
                                for j, v in enumerate(q)]] for i in range(0, 76)]


plate = json.load(open(os.path.join(ROOT, "media/shots/D3/track_plate_v9_r2.json")))["keys"]
out = os.path.join(ROOT, "tools/v9/mirrors/d3_tracks_r2.js")
with open(out, "w") as f:
    f.write("// v9 fix #2 round 2 (D3): generated by tools/v9/mirrors/d3_tracks_r2.py for media/shots/D3/v9_take_2_push_r2.mp4.\n")
    f.write("// [layer_t, [TLx,TLy, TRx,TRy, BRx,BRy, BLx,BLy]] in design px, as the engine's `corners` keys.\n")
    f.write("export const D3_PLATE_R2 = " + json.dumps(plate) + ";\n")
    f.write("export const D3_ETCH_L_R2 = " + json.dumps(keys(ETCH_L)) + ";\n")
    f.write("export const D3_ETCH_R_R2 = " + json.dumps(keys(ETCH_R)) + ";\n")
print("wrote", os.path.relpath(out, ROOT))
